"""Writes stan_reference_scalar.cpp: Stan values and gradients for every function of one or two
reals in the Stan language, except the _rng and bound transform functions.

    stanc --dump-stan-math-signatures > sigs.txt
    python3 tools/stan-reference/gen_scalar.py sigs.txt
"""

import re
import sys

HERE = "tools/stan-reference"
# Language names whose Stan Math C++ function has another name.
CPP = {"std_normal_qf": "inv_Phi", "lchoose": "binomial_coefficient_log"}


def names(sigs, args):
    pat = re.compile(r"([A-Za-z_0-9]+)\(" + re.escape(args) + r"\) => real")
    found = [m.group(1) for m in map(pat.fullmatch, sigs) if m]
    keep = [n for n in found if not n.endswith("_rng") and not n.startswith(("lower_bound", "upper_bound"))]
    return list(dict.fromkeys(keep))


def main():
    sigs = open(sys.argv[1]).read().splitlines()
    src = open(f"{HERE}/stan_reference_extra.cpp").read()
    head = src[: src.index("int main() {")]
    head = head.split("\n", 2)[2]
    lines = [
        f'  continuous("{n}", U, [](const Vars& v) {{ return {CPP.get(n, n)}(v[0]); }});'
        for n in names(sigs, "real")
    ] + [
        f'  continuous("{n}", B, [](const Vars& v) {{ return {CPP.get(n, n)}(v[0], v[1]); }});'
        for n in names(sigs, "real, real")
    ]
    out = (
        "// Reference values and gradients from Stan Math for every function of one or two reals in\n"
        "// the Stan language except the _rng and bound transform functions. Written by gen_scalar.py.\n"
        + head
        + "int main() {\n  using namespace stan::math;\n"
        + '  std::cout << "# Generated by tools/stan-reference/stan_reference_scalar.cpp\\n";\n'
        + "  const Pts U = {{0.3}, {0.75}, {1.7}, {-0.6}, {-0.2}, {4.2}};\n"
        + "  const Pts B = {{0.3, 0.7}, {1.7, 2.5}, {-0.6, 1.3}, {4.2, 0.9}, {2.0, 2.0}};\n"
        + "\n".join(lines)
        + "\n}\n"
    )
    open(f"{HERE}/stan_reference_scalar.cpp", "w").write(out)


main()
