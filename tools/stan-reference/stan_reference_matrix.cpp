std::string join(const std::vector<double>& v) {
  std::ostringstream os;
  os << std::setprecision(17);
  for (std::size_t i = 0; i < v.size(); ++i) {
    if (i) os << ';';
    os << v[i];
  }
  return os.str();
}

std::string join_int(const std::vector<int>& v) {
  std::ostringstream os;
  for (std::size_t i = 0; i < v.size(); ++i) {
    if (i) os << ';';
    os << v[i];
  }
  return os.str();
}

void emit(const std::string& name, const std::vector<int>& ints,
          const std::vector<double>& x,
          const std::function<var(const std::vector<int>&, const Vars&)>& f) {
  Vars xv(x.begin(), x.end());
  std::cout << name << ',' << join_int(ints) << ',' << join(x) << ',';
  try {
    var lp = f(ints, xv);
    lp.grad();
    std::vector<double> g;
    for (auto& v : xv) g.push_back(v.adj());
    std::cout << std::setprecision(17) << lp.val() << ',' << join(g) << '\n';
  } catch (const std::exception&) {
    std::cout << "error,\n";
  }
  stan::math::recover_memory();
}

using Pts = std::vector<std::vector<double>>;

template <typename F>
void continuous(const std::string& name, const Pts& pts, F f) {
  for (const auto& p : pts) {
    emit(name, {}, p, [&](const std::vector<int>&, const Vars& v) { return f(v); });
  }
}

template <typename F>
void discrete(const std::string& name,
              const std::vector<std::pair<std::vector<int>, std::vector<double>>>& pts, F f) {
  for (const auto& p : pts) {
    emit(name, p.first, p.second, f);
  }
}


using M3 = Eigen::Matrix<var, -1, -1>;
using V = Eigen::Matrix<var, -1, 1>;

// A 3 by 3 lower triangular matrix from six values, row by row.
M3 low(const Vars& v, int o) {
  M3 m = M3::Zero(3, 3);
  m(0, 0) = v[o]; m(1, 0) = v[o + 1]; m(1, 1) = v[o + 2];
  m(2, 0) = v[o + 3]; m(2, 1) = v[o + 4]; m(2, 2) = v[o + 5];
  return m;
}

// A 3 by 3 symmetric matrix from its lower triangle, row by row.
M3 sym(const Vars& v, int o) {
  M3 m(3, 3);
  m(0, 0) = v[o]; m(1, 0) = m(0, 1) = v[o + 1]; m(1, 1) = v[o + 2];
  m(2, 0) = m(0, 2) = v[o + 3]; m(2, 1) = m(1, 2) = v[o + 4]; m(2, 2) = v[o + 5];
  return m;
}

V vec(const Vars& v, int o, int n) {
  V r(n);
  for (int i = 0; i < n; ++i) r(i) = v[o + i];
  return r;
}

std::vector<var> arr(const Vars& v, int o, int n) { return Vars(v.begin() + o, v.begin() + o + n); }


using MV = Eigen::Matrix<var, -1, -1>;

MV mat(const Vars& v, int o, int r, int c) {
  MV m(r, c);
  for (int k = 0; k < r * c; ++k) m(k % r, k / r) = v[o + k];
  return m;
}

template <typename E>
var wsum(const E& e) {
  MV m = e;
  var s = 0;
  for (int k = 0; k < m.size(); ++k) s += (1.0 + 0.1 * k) * m(k % m.rows(), k / m.rows());
  return s;
}

var wsum(const std::vector<var>& e) {
  var s = 0;
  for (std::size_t k = 0; k < e.size(); ++k) s += (1.0 + 0.1 * k) * e[k];
  return s;
}

var wsum(const var& e) { return e; }

