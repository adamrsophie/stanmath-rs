// Reference values and gradients from Stan Math for the matrix functions and constraining
// transforms of the Stan language. A matrix or vector result is reduced to the weighted sum
// sum_k (1 + k / 10) r_k over its column major entries, so one gradient checks every entry; a
// _jacobian case adds the log Jacobian to that sum.
//
// Inputs: A is a general 3 by 3 matrix (9 values, column major); B is 3 by 2 (6 values); S, C, and
// L are a symmetric positive definite, a correlation, and a lower triangular 3 by 3 matrix built
// from 6 values (see sym and low); v is a vector of 3 or 4 values.
//
// Each output line is
//   function,ints,reals,value,gradient
// as in stan_reference_extra.cpp.

