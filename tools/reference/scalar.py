"""High-precision values and gradients for the rows of stan_reference_scalar.csv where Stan Math
is less accurate than stanmath-rs: digamma, trigamma, the standard normal log CDFs, gamma_q, and
the chi-square and inverse chi-square CDFs.

Run from the repository root:

    uv run --with mpmath python tools/reference/scalar.py

Writes crates/stanmath-rs/tests/data/mpmath_reference_scalar.csv in the fixture's format.
"""

import csv
import os
from mpmath import mp, mpf, diff, log, psi, ncdf, gammainc, inf

mp.dps = 40
DATA = "crates/stanmath-rs/tests/data"


def P(a, x):
    return gammainc(a, 0, x, regularized=True)


def Q(a, x):
    return gammainc(a, x, inf, regularized=True)


F = {
    "digamma": lambda x: psi(0, x[0]),
    "trigamma": lambda x: psi(1, x[0]),
    "std_normal_lcdf": lambda x: log(ncdf(x[0])),
    "std_normal_lccdf": lambda x: log(1 - ncdf(x[0])),
    "gamma_q": lambda x: Q(x[0], x[1]),
    "chi_square_cdf": lambda x: P(x[1] / 2, x[0] / 2),
    "chi_square_lcdf": lambda x: log(P(x[1] / 2, x[0] / 2)),
    "chi_square_lccdf": lambda x: log(Q(x[1] / 2, x[0] / 2)),
    "inv_chi_square_cdf": lambda x: Q(x[1] / 2, 1 / (2 * x[0])),
    "inv_chi_square_lcdf": lambda x: log(Q(x[1] / 2, 1 / (2 * x[0]))),
    "inv_chi_square_lccdf": lambda x: log(P(x[1] / 2, 1 / (2 * x[0]))),
}


def main():
    rows = []
    with open(os.path.join(DATA, "stan_reference_scalar.csv")) as f:
        for line in f:
            if line.startswith("#"):
                continue
            name, ints, reals, value = line.strip().split(",")[:4]
            if name not in F or value == "error":
                continue
            x = [mpf(v) for v in reals.split(";")]
            g = F[name]
            grad = [diff(lambda t, k=k: g(x[:k] + [t] + x[k + 1:]), x[k]) for k in range(len(x))]
            fmt = lambda v: mp.nstr(v, 20, strip_zeros=False)
            rows.append([name, ints, reals, fmt(g(x)), ";".join(fmt(v) for v in grad)])
    with open(os.path.join(DATA, "mpmath_reference_scalar.csv"), "w", newline="") as f:
        f.write("# Generated by tools/reference/scalar.py with mpmath at 40 digits\n")
        csv.writer(f, lineterminator="\n").writerows(rows)


main()
